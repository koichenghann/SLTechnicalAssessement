-- Task Management API schema (PostgreSQL).
-- Run once against the target database before starting the application, then run seed-data.sql.
-- Roles, statuses and timestamps are enforced by the application, so the schema only keeps
-- keys, required columns and the indexes used by task queries.

CREATE TABLE users (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username    VARCHAR(50)  NOT NULL UNIQUE,
    password    VARCHAR(100) NOT NULL,
    full_name   VARCHAR(100),
    role        VARCHAR(20)  NOT NULL,
    created_dts TIMESTAMP WITH TIME ZONE
);

CREATE TABLE tasks (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title         VARCHAR(150) NOT NULL,
    description   VARCHAR(2000),
    status        VARCHAR(20)  NOT NULL,
    assigned_uid  BIGINT REFERENCES users (id),
    created_uid   BIGINT NOT NULL REFERENCES users (id),
    created_dts   TIMESTAMP WITH TIME ZONE,
    updated_dts   TIMESTAMP WITH TIME ZONE
);

CREATE INDEX idx_tasks_title ON tasks (title);
CREATE INDEX idx_tasks_assigned_uid ON tasks (assigned_uid);
CREATE INDEX idx_tasks_status ON tasks (status);
